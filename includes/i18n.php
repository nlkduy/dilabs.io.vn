$supportedLangs = array_keys($translations);

$lang = $_GET['lang'] ?? $_COOKIE['language'] ?? 'en';
if (!in_array($lang, $supportedLangs, true)) {
    $lang = 'en';
}

if (($_COOKIE['language'] ?? null) !== $lang) {
    setcookie('language', $lang, time() + 365 * 24 * 60 * 60, '/');
}

/**
 * Translate a key in the current language, HTML-escaped.
 */
function t(string $key): string
{
    global $translations, $lang;
    return htmlspecialchars($translations[$lang][$key] ?? $key, ENT_QUOTES, 'UTF-8');
}
